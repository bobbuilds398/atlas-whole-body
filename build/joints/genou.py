from zalib import *
fem,tib,fib,pat='Femur','Tibia','Fibula','Patella'
top=V(tib)[:,2].max()
plat=ext(tib,'up',frac=.05)
pm=ext(tib,'med',where=zband(top-14,top));pl=ext(tib,'lat',where=zband(top-14,top))
em=ext(fem,'med',where=zband(top,top+50));el=ext(fem,'lat',where=zband(top,top+50))
apex=ext(pat,'down');pbase=ext(pat,'up');pc=cen(pat)
tta=ext(tib,'front',where=zband(top-62,top-28))
J=Joint('genou','Genou','Genou droit',mix(plat,pc,.4),430)
J.use()
J.bone('femur','Fémur',fem);J.bone('tibia','Tibia',tib);J.bone('fibula','Fibula',fib,cap=3000);J.bone('patella','Rotule',pat,cap=2500)
J.real('men-med','Ménisque médial','cart','Medial meniscus',color='#9fd8ee',op=.95)
J.real('men-lat','Ménisque latéral','cart','Lateral meniscus',color='#9fd8ee',op=.95)
J.real('lca','Ligament croisé antérieur','lig','Anterior cruciate ligament')
J.real('lcp','Ligament croisé postérieur','lig','Posterior cruciate ligament')
J.real('lcm','Ligament collatéral médial','lig',['Superficial part of tibial collateral ligament','Deep part of tibial collateral ligament'])
J.real('lcl','Ligament collatéral latéral','lig','Fibular collateral ligament')
J.real('lpo','Ligament poplité oblique','lig','Oblique popliteal ligament')
J.real('ret','Ailerons rotuliens','lig',['Medial patellar retinaculum','Lateral patellar retinaculum'],op=.5)
J.real('hoffa','Coussinet graisseux sous la rotule','cart','Infrapatellar fat pad',color='#e8d98a',op=.6)
J.real('b-pre','Bourses prérotuliennes','cart',['Subcutaneous prepatellar bursa','Subtendinous prepatellar bursa','Subfacial prepatellar bursa'],op=.75)
J.real('b-inf','Bourses sous la rotule','cart',['Deep infrapatellar bursa','Subcutaneous infrapatellar bursa','Subcutaneous bursa of tuberosity of tibia'],op=.75)
J.real('b-sup','Bourse suprapatellaire','cart','Suprapatellar bursa',op=.5)
J.real('b-pes','Bourse de la patte d’oie','cart','Anserine bursa',op=.8)
J.real('baker','Bourses du creux poplité','cart',['Semimembranosus bursa','Medial subtendinous bursa of gastrocnemius muscle'],op=.8)
J.mus('quad','Quadriceps',['Rectus femoris muscle','Vastus lateralis muscle','Vastus medialis muscle','Vastus intermedius muscle'],tlabel='Tendon quadricipital et tendon rotulien')
J.mus('biceps','Biceps fémoral',['Long head of biceps femoris','Short head of biceps femoris'])
J.mus('ischio','Semi-membraneux et semi-tendineux',['Semimembranosus muscle','Semitendinosus muscle'])
J.mus('pattes','Sartorius et gracile',['Sartorius muscle','Gracilis muscle'])
J.mus('gastro','Jumeaux du mollet',['Medial head of gastrocnemius','Lateral head of gastrocnemius'])
J.mus('popl','Muscle poplité','Popliteus muscle')
J.real('itb','Bandelette ilio-tibiale','ten','Iliotibial tract',cap=5000,op=.55)
J.real('n-fib','Nerf fibulaire commun','nerf','Common fibular nerve',cap=1200)
J.real('n-tib','Nerf tibial','nerf','Tibial nerve',cap=1500)
J.ent('e-rot','Attaches du tendon rotulien',['Patellar ligament.o','Patellar ligament.e'])
J.ent('e-quad','Attache du tendon quadricipital','Quadriceps femoris muscle.e')
J.ent('e-pes','Attache de la patte d’oie',['Sartorius muscle.e','Gracilis muscle.e','Semitendinosus muscle.e'])
J.skin([pc],190)
pes=np.mean([ins('Sartorius muscle'),ins('Gracilis muscle'),ins('Semitendinosus muscle')],0)
gerdy=ins('Iliotibial tract') if has('Iliotibial tract.er','') else ext(tib,'lat+front',where=zband(top-30,top-8))
cm=cen('Medial meniscus');cl=cen('Lateral meniscus');mmpost=ext('Medial meniscus','back')
lca=cen('Anterior cruciate ligament');lcm=V('Superficial part of tibial collateral ligament')
lcm_hi=ext(lcm,'up',frac=.1);lcm_mid=lcm.mean(0)
bk=cen('Semimembranosus bursa');pre=cen('Subcutaneous prepatellar bursa')
for a in [('avant','w','À l’avant du genou, autour de la rotule'),('dedans','w','Sur le côté intérieur'),('dehors','w','Sur le côté extérieur'),('arriere','w','À l’arrière du genou'),('dessous','w','Juste sous la rotule'),
 ('escalier','q','Dans les escaliers ou accroupi'),('assis','q','Après être resté assis longtemps'),('course','q','En courant ou en sautant'),('torsion','q','Après une torsion ou un choc'),('gonfle','q','Le genou gonfle'),('bloque','q','Ça bloque ou ça accroche'),('lache','q','Le genou se dérobe'),('raide','q','Raide au lever'),('genoux','q','À genoux ou à l’appui dessus'),('ado','q','Adolescent en pleine croissance')]: J.sym(*a)
p=J.p
p('sfp',['c-patella','patella','ret'],[(off(pc,'back',8),26)],[(off(pc,'front',8),50)],tags=['avant','escalier','assis','course'])
p('gonarthrose',['c-femur','c-tibia','men-med','men-lat'],[(cm+vec('up')*4,30),(cl+vec('up')*4,22)],[(off(pm,'front',15),55),(pc,40)],tags=['dedans','avant','escalier','raide','gonfle'])
p('menisque',['men-med'],[(mmpost,16),(cm,14)],[(off(pm,'back',10),40)],tags=['dedans','torsion','bloque','gonfle','escalier'])
p('rotulien',['e-rot','t-quad','patella'],[(cen('Patellar ligament.or'),15)],[(off(apex,'front',6),26)],tags=['dessous','avant','course','escalier'])
p('tfl',['itb'],[(off(el,'lat',3),24)],[(off(el,'lat',8),42)],tags=['dehors','course'])
p('lcm',['lcm'],[(lcm_hi,20),(lcm_mid,22)],[(lcm_mid+vec('med')*6,45)],tags=['dedans','torsion','gonfle','lache'])
p('lca',['lca'],[(lca,26)],[(pc,62)],tags=['torsion','gonfle','lache'])
p('pes',['e-pes','b-pes','t-pattes','t-ischio'],[(pes,20)],[(off(pes,'med',5),36)],tags=['dedans','dessous','escalier','course'])
p('osgood',['e-rot','t-quad','tibia','b-inf'],[(cen('Patellar ligament.er'),16)],[(off(tta,'front',5),28)],tags=['dessous','ado','course','genoux'])
p('baker',['baker'],[(bk,30)],[(off(bk,'back',14),45)],tags=['arriere','gonfle','raide'])
p('prerot',['b-pre'],[(pre,28)],[(off(pre,'front',6),40)],tags=['avant','genoux','gonfle'])
p('quadri',['e-quad','t-quad','patella'],[(cen('Quadriceps femoris muscle.er'),17)],[(off(pbase,'front',6),28)],tags=['avant','escalier','course'])
J.write()
