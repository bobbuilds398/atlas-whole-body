from zalib import *
sc,cl,hu='Scapula','Clavicle','Humerus'
htop=V(hu)[:,2].max()
acr=ext(sc,'lat+0.6up');cor=ext(sc,'front')
g=cen('Glenoid labrum');hh=g+vec('lat')*22
J=Joint('epaule','Épaule','Épaule droite',mix(hh,acr,.3),420)
J.use()
J.bone('humerus','Humérus',hu);J.bone('scapula','Omoplate',sc);J.bone('clavicule','Clavicule',cl,cap=3500)
J.bone('cotes','Côtes',['First rib','Second rib','Third rib','Fourth rib','Fifth rib','Sixth rib','Seventh rib'],cap=1400,cart=False)
J.real('labrum','Bourrelet glénoïdien','cart','Glenoid labrum',color='#9fd8ee',op=.95)
J.real('capsule','Capsule de l’articulation','lig','Articular capsule of glenohumeral joint',color='#cfe3ee',op=.22)
J.real('lgh','Ligaments gléno-huméraux','lig',['Superior glenohumeral ligament','Middle glenohumeral ligament','Inferior glenohumeral ligament'])
J.real('lch','Ligament coraco-huméral','lig','Coracohumeral ligament')
J.real('lca','Ligament coraco-acromial','lig','Coraco-acromial ligament')
J.real('lac','Articulation acromio-claviculaire','lig',['Acromioclavicular ligament','Articular capsule of acromioclavicular joint'])
J.real('dac','Disque acromio-claviculaire','cart','Articular disc of acromioclavicular joint',op=.9)
J.real('lcc','Ligaments coraco-claviculaires','lig',['Conoid ligament','Trapezoid ligament'])
J.real('bsa','Bourse sous-acromiale et sous-deltoïdienne','cart',['Subacromial bursa','Subdeltoid bursa'],op=.6)
J.real('gaine','Gaine du long biceps','ten',['Intertubercular tendon sheath','Transverse humeral ligament'],color='#f6efe0',op=.7)
se=I_('Supraspinatus muscle','e');ie=I_('Infraspinatus muscle','e');sse=I_('Subscapularis muscle','e')
J.mus('supra','Supra-épineux','Supraspinatus muscle',tlabel='Tendon du supra-épineux',tp=[(se,34)])
J.mus('infra','Infra-épineux','Infraspinatus muscle',tlabel='Tendon de l’infra-épineux',tp=[(ie,30)])
J.mus('subscap','Sous-scapulaire','Subscapularis muscle',tlabel='Tendon du sous-scapulaire',tp=[(sse,30)])
J.mus('tmin','Petit rond','Teres minor muscle')
J.mus('delt','Deltoïde',['Acromial part of deltoid muscle','Clavicular part of deltoid muscle','Scapular spinal part of deltoid muscle'])
J.mus('bicl','Long biceps','Long head of biceps brachii',tlabel='Tendon du long biceps')
J.mus('bicc','Court biceps et coraco-brachial',['Short head of biceps brachii','Coracobrachialis muscle'])
J.mus('pmin','Petit pectoral','Pectoralis minor muscle')
J.mus('dent','Dentelé antérieur','Serratus anterior muscle',cap=6000)
J.mus('trap','Trapèze',['Descending part of trapezius muscle','Transverse part of trapezius muscle','Ascending part of trapezius muscle'])
J.mus('rhomb','Rhomboïdes',['Rhomboid major muscle','Rhomboid minor muscle'])
J.mus('lev','Élévateur de la scapula','Levator scapulae')
J.mus('tmaj','Grand rond','Teres major muscle')
J.real('n-sus','Nerf supra-scapulaire','nerf','Suprascapular nerve',cap=900)
J.real('n-ax','Nerf axillaire','nerf','Axillary nerve',cap=900)
J.real('n-lt','Nerf thoracique long','nerf','Long thoracic nerve',cap=900)
J.skin([hh,mix(hh,cen(sc))],200)
J.ent('e-coiffe','Attaches de la coiffe sur l’humérus',['Supraspinatus muscle.e','Infraspinatus muscle.e','Teres minor muscle.e'])
J.ent('e-subscap','Attache du sous-scapulaire','Subscapularis muscle.e')
J.ent('e-bicl','Attache du long biceps sur la glène','Long head of biceps brachii.o')
groove=cen('Intertubercular tendon sheath');lbo=I_('Long head of biceps brachii','o',g+vec('up')*15)
ac=cen('Articular disc of acromioclavicular joint');bsa=cen('Subacromial bursa')
calc=mix(se,cen('Supraspinatus muscle'),.16)
J.blob('calc','Dépôt calcaire, lorsqu’il existe','ten',calc,(6,4,3.5),color='#ffffff')
mb=ext(sc,'med');ib=ext(sc,'down')
for a in [('cote','w','Sur le côté de l’épaule et du bras'),('devant','w','À l’avant de l’épaule'),('dessus','w','Sur le dessus de l’épaule'),('omoplate','w','Autour de l’omoplate'),('profond','w','Profond, difficile à situer'),
 ('lever','q','En levant le bras'),('nuit','q','La nuit, couché sur l’épaule'),('raide','q','L’épaule devient raide'),('force','q','Le bras manque de force'),('porter','q','En portant un objet devant soi'),('croiser','q','En croisant le bras devant la poitrine'),('lancer','q','En lançant ou bras armé en arrière'),('deboite','q','L’épaule se déboîte ou menace de sortir'),('chute','q','Après une chute'),('crise','q','Crise très violente de quelques jours')]: J.sym(*a)
p=J.p
p('coiffe',['e-coiffe','t-supra','m-supra','t-infra'],[(se,20)],[(off(se,'lat',10),42),(off(se,'down+0.3lat',80),40)],tags=['cote','lever','nuit'])
p('conflit',['bsa','lca','t-supra'],[(bsa,26)],[(off(acr,'lat+0.4front',10),45)],tags=['cote','dessus','lever'])
p('capsulite',['capsule','lgh','lch'],[(hh,38)],[(off(hh,'lat',25),60),(off(hh,'front',25),50)],tags=['profond','raide','nuit','cote'])
p('rupture',['e-coiffe','t-supra','m-supra','t-infra','m-infra'],[(se,17),(cen('Supraspinatus muscle'),36)],[(off(se,'lat',8),45)],tags=['cote','force','nuit','chute','lever'])
p('biceps',['t-bicl','gaine','m-bicl'],[(groove,18),(groove+vec('up')*16,12)],[(off(groove,'front',10),36)],tags=['devant','porter'])
p('ac',['lac','dac','lcc','clavicule'],[(ac,16)],[(off(ac,'up',6),30)],tags=['dessus','croiser','nuit','chute'],view='dessus')
p('calc',['calc','t-supra','bsa'],[(calc,15)],[(off(calc,'lat+0.5up',10),45)],tags=['cote','crise','nuit'])
p('instab',['labrum','lgh','capsule'],[(ext('Glenoid labrum','front+down',frac=.2),18)],[(off(hh,'front',28),48)],tags=['devant','deboite','lancer'])
p('omarthrose',['c-humerus','c-scapula','labrum'],[(g+vec('lat')*8,28)],[(off(hh,'lat',25),55)],tags=['profond','raide','nuit'])
p('slap',['e-bicl','labrum','t-bicl'],[(lbo,14)],[(off(hh,'up+0.5back',25),40)],tags=['profond','lancer'])
p('dysk',['m-dent','m-trap','m-rhomb','scapula','n-lt'],[(mix(mb,ib,.5),45),(cen('Serratus anterior muscle'),55)],[(mix(mb,ib,.5)+vec('back')*20,65)],tags=['omoplate','lever'],view='dos')
p('subscap',['e-subscap','t-subscap','m-subscap'],[(sse,16)],[(off(sse,'front+0.5med',12),36)],tags=['devant','lancer'])
J.write()
