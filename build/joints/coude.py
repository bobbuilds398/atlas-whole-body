from zalib import *
hu,ra,ul='Humerus','Radius','Ulna'
zlo=V(hu)[:,2].min()
elat=ext(hu,'lat',where=zband(zlo,zlo+32));emed=ext(hu,'med',where=zband(zlo,zlo+32))
olec=ext(ul,'up');rh=ext(ra,'up',frac=.04);jc=mix(elat,emed,.5)
dist=cen(ra)-rh;dist/=np.linalg.norm(dist)
fr=np.cross(emed-elat,dist);fr/=np.linalg.norm(fr)
if fr@vec('front')<0: fr=-fr
bk=-fr
J=Joint('coude','Coude','Coude droit',jc,330)
J.use()
J.bone('humerus','Humérus',hu);J.bone('radius','Radius',ra);J.bone('ulna','Ulna',ul)
J.real('lcu','Ligament collatéral médial','lig','Ulnar collateral ligament')
J.real('lcr','Ligament collatéral latéral','lig','Radial collateral ligament')
J.real('lan','Ligament annulaire','lig','Annular ligament of radius')
J.real('capsule','Capsule de l’articulation','lig','Articular capsule of elbow joint',color='#cfe3ee',op=.2)
J.real('b-bic','Bourse du biceps','cart','Bicipitoradial bursa',op=.75)
J.real('b-tri','Bourse sous le tendon du triceps','cart','Subtendinous bursa of triceps brachii muscle',op=.75)
bol=olec+bk*8+dist*8
J.blob('bol','Bourse de l’olécrâne','cart',bol,(12,6,17),op=.6)
J.mus('ecrb','Court extenseur radial du carpe','Extensor carpi radialis brevis',tlabel='Tendon du court extenseur radial du carpe')
J.mus('ext','Extenseurs du poignet et des doigts',['Extensor carpi radialis longus','Extensor digitorum','Extensor digiti minimi','Humeral head of extensor carpi ulnaris','Ulnar head of extensor carpi ulnaris'],tlabel='Tendons des extenseurs')
J.mus('brad','Brachio-radial','Brachioradialis muscle')
J.mus('sup','Supinateur','Supinator')
J.mus('flech','Fléchisseurs du poignet et des doigts',['Flexor carpi radialis','Palmaris longus muscle','Humeral head of flexor carpi ulnaris','Ulnar head of flexor carpi ulnaris','Humero-ulnar head of flexor digitorum superficialis','Radial head of flexor digitorum superficialis'],tlabel='Tendons des fléchisseurs')
J.mus('pron','Rond pronateur',['Superficial head of pronator teres','Deep head of pronator teres'])
J.mus('bic','Biceps',['Long head of biceps brachii','Short head of biceps brachii'],tlabel='Tendon du biceps')
J.mus('brach','Brachial','Brachialis muscle')
J.mus('tri','Triceps',['Long head of triceps brachii','Lateral head of triceps brachii','Medial head of triceps brachii'],tlabel='Tendon du triceps')
J.mus('anc','Anconé','Anconeus muscle')
J.real('nu','Nerf ulnaire','nerf','Ulnar nerve',cap=2500)
J.real('nr','Nerf radial et sa branche profonde','nerf',['Radial nerve','Deep branch of radial nerve','Posterior interosseous nerve of forearm'],cap=2000)
J.real('nm','Nerf médian','nerf','Median nerve',cap=2500)
J.ent('e-ext','Attache commune des extenseurs','Common extensor tendon.o')
J.ent('e-flech','Attache commune des fléchisseurs',['Common flexor tendon.o','Pronator teres.o'])
J.ent('e-bic','Attache du biceps sur le radius','Biceps brachii muscle.e')
J.ent('e-tri','Attache du triceps sur l’olécrâne','Triceps brachii muscle.e')
J.skin([jc],170)
eo=I_('Common extensor tendon','o');fo=I_('Common flexor tendon','o')
be=I_('Biceps brachii muscle','e');te=I_('Triceps brachii muscle','e')
nu_c=snap('Ulnar nerve',emed+bk*12);nr_c=snap('Deep branch of radial nerve',cen('Supinator'));nm_c=snap('Median nerve',cen('Superficial head of pronator teres'))
cap=near(hu,ra);fos=mix(olec,jc,.55)+bk*4-dist*8;lcu=cen('Ulnar collateral ligament')
for a in [('dehors','w','Sur le côté extérieur du coude'),('dedans','w','Sur le côté intérieur du coude'),('pointe','w','À la pointe ou à l’arrière du coude'),('pli','w','Au pli du coude'),('avantbras','w','Dans l’avant-bras'),
 ('serrer','q','En serrant ou en vissant'),('porter','q','En portant une charge'),('pousser','q','En poussant ou en tendant le bras'),('lancer','q','En lançant'),('fourmi45','q','Fourmillements du petit doigt'),('fourmi123','q','Fourmillements du pouce et de l’index'),('boule','q','Une boule est apparue'),('raide','q','Le coude est raide ou se bloque'),('appui','q','À l’appui sur le coude'),('ado','q','Adolescent sportif')]: J.sym(*a)
p=J.p
p('epicondylite',['e-ext','t-ecrb','m-ecrb','t-ext'],[(eo,16)],[(off(eo,'lat',6),32),(eo+dist*55+vec('lat')*6,32)],tags=['dehors','serrer','porter'],view='cote')
p('epitro',['e-flech','t-flech','m-flech','m-pron'],[(fo,16)],[(off(fo,'med',6),32)],tags=['dedans','serrer','lancer'],view='dedans')
p('bursite',['bol'],[(bol,24)],[(bol+bk*6,34)],tags=['pointe','boule','appui'],view='dos')
p('ulnaire',['nu'],[(nu_c,20),(nu_c+dist*30,14)],[(nu_c+bk*4,30),(nu_c+dist*95,28)],tags=['dedans','fourmi45','appui'],view='dedans')
p('bicepsd',['e-bic','t-bic','b-bic','m-bic'],[(be,17)],[(jc+fr*22,36)],tags=['pli','porter','serrer'])
p('triceps',['e-tri','t-tri','b-tri','m-tri'],[(te,17)],[(te+bk*8-dist*8,32)],tags=['pointe','pousser'],view='dos')
p('arthrose',['c-humerus','c-radius','c-ulna'],[(jc,26),(cap,18)],[(jc+bk*14,46)],tags=['raide','pointe','pousser'])
p('lcu',['lcu'],[(lcu,17)],[(lcu+vec('med')*6,30)],tags=['dedans','lancer'],view='dedans')
p('radial',['nr','m-sup'],[(nr_c,20)],[(nr_c+vec('lat')*8+fr*4,36)],tags=['avantbras','dehors','serrer'],view='cote')
p('pronateur',['nm','m-pron'],[(nm_c,20)],[(nm_c+fr*10,38)],tags=['avantbras','pli','fourmi123','serrer'])
p('conflit',['c-humerus','c-ulna','ulna'],[(fos,16)],[(fos+bk*8,30)],tags=['pointe','pousser','raide','lancer'],view='dos')
p('ocd',['c-humerus','c-radius'],[(cap,14)],[(off(cap,'lat',10),30)],tags=['dehors','ado','raide','lancer'],view='cote')
J.write()
